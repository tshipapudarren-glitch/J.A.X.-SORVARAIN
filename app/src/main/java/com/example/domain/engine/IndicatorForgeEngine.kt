    fun sanitizeFileStem(name: String): String {
        val cleaned = name.replace(Regex("[^a-zA-Z0-9]+"), "_").trim('_')
        return if (cleaned.isBlank()) "JAX_Custom_Indicator" else "JAX_${cleaned.take(40)}"
    }

    fun generateMql5Source(
        name: String,
        category: ForgeCategory,
        pattern: SetupDrawingPattern,
        mtfTimeframes: List<String>,
        fastPeriod: Int,
        slowPeriod: Int,
        atrPeriod: Int,
        rrTarget: Double,
        drawing: SetupDrawingConfig
    ): String {
        val htf = mtfTimeframes.firstOrNull() ?: "H1"
        val mtfEnum = toMql5Period(htf)
        val entryClr = toMql5Color(drawing.entryColorHex, "clrGold")
        val slClr = toMql5Color(drawing.slColorHex, "clrCrimson")
        val tp1Clr = toMql5Color(drawing.tp1ColorHex, "clrMediumSeaGreen")
        val tp2Clr = toMql5Color(drawing.tp2ColorHex, "clrLimeGreen")
        val tp3Clr = toMql5Color(drawing.tp3ColorHex, "clrDeepSkyBlue")
        val invClr = toMql5Color(drawing.invalidationColorHex, "clrOrange")

        return """
//+------------------------------------------------------------------+
//| ${name}.mq5
//| Generated by J.A.X. OMNIVERSE — Indicator Forge
//| Category: ${category.label} | Pattern: ${pattern.label}
//+------------------------------------------------------------------+
#property copyright "J.A.X. OMNIVERSE"
#property version   "1.00"
#property strict
#property indicator_chart_window
#property indicator_buffers 4
#property indicator_plots   4

#property indicator_label1  "JAX Fast EMA"
#property indicator_type1   DRAW_LINE
#property indicator_color1  clrGold
#property indicator_width1  2

#property indicator_label2  "JAX Slow EMA"
#property indicator_type2   DRAW_LINE
#property indicator_color2  clrDeepSkyBlue
#property indicator_width2  2

#property indicator_label3  "JAX Buy Signal"
#property indicator_type3   DRAW_ARROW
#property indicator_color3  clrLime
#property indicator_width3  2

#property indicator_label4  "JAX Sell Signal"
#property indicator_type4   DRAW_ARROW
#property indicator_color4  clrRed
#property indicator_width4  2

//--- Configurable Inputs
input ENUM_TIMEFRAMES InpConfirmTF       = $mtfEnum;       // Higher Timeframe Bias
input int             InpFastEma         = $fastPeriod;    // Fast Trend EMA
input int             InpSlowEma         = $slowPeriod;    // Slow Structure EMA
input int             InpAtrPeriod       = $atrPeriod;     // Volatility ATR Period
input int             InpSwingLookback   = 20;             // Liquidity / Structure Lookback
input double          InpTargetRR        = ${String.format("%.2f", rrTarget)}; // Primary TP2 Risk:Reward
input bool            InpClosedCandleOnly= ${drawing.closedCandleOnly}; // Non-repainting Closed Bar
input bool            InpDrawSetupBoxes  = ${drawing.showRiskRewardBoxes}; // Draw Entry/SL/TP1-3
input int             InpLineWidth       = ${drawing.lineWidthPx.coerceIn(1, 5)};
input color           InpEntryColor      = $entryClr;
input color           InpSlColor         = $slClr;
input color           InpTp1Color        = $tp1Clr;
input color           InpTp2Color        = $tp2Clr;
input color           InpTp3Color        = $tp3Clr;
input color           InpInvalidColor    = $invClr;

double BufFastEma[];
double BufSlowEma[];
double BufBuyArrow[];
double BufSellArrow[];

int hFast = INVALID_HANDLE;
int hSlow = INVALID_HANDLE;
int hAtr  = INVALID_HANDLE;
int hHtfFast = INVALID_HANDLE;
int hHtfSlow = INVALID_HANDLE;
datetime lastSignalBar = 0;

int OnInit()
  {
   SetIndexBuffer(0, BufFastEma, INDICATOR_DATA);
   SetIndexBuffer(1, BufSlowEma, INDICATOR_DATA);
   SetIndexBuffer(2, BufBuyArrow, INDICATOR_DATA);
   SetIndexBuffer(3, BufSellArrow, INDICATOR_DATA);

   PlotIndexSetInteger(2, PLOT_ARROW, 233);
   PlotIndexSetInteger(3, PLOT_ARROW, 234);
   PlotIndexSetDouble(2, PLOT_EMPTY_VALUE, EMPTY_VALUE);
   PlotIndexSetDouble(3, PLOT_EMPTY_VALUE, EMPTY_VALUE);

   ArraySetAsSeries(BufFastEma, true);
   ArraySetAsSeries(BufSlowEma, true);
   ArraySetAsSeries(BufBuyArrow, true);
   ArraySetAsSeries(BufSellArrow, true);

   hFast    = iMA(_Symbol, _Period, InpFastEma, 0, MODE_EMA, PRICE_CLOSE);
   hSlow    = iMA(_Symbol, _Period, InpSlowEma, 0, MODE_EMA, PRICE_CLOSE);
   hAtr     = iATR(_Symbol, _Period, InpAtrPeriod);
   hHtfFast = iMA(_Symbol, InpConfirmTF, InpFastEma, 0, MODE_EMA, PRICE_CLOSE);
   hHtfSlow = iMA(_Symbol, InpConfirmTF, InpSlowEma, 0, MODE_EMA, PRICE_CLOSE);

   if(hFast == INVALID_HANDLE || hSlow == INVALID_HANDLE || hAtr == INVALID_HANDLE)
      return(INIT_FAILED);

   return(INIT_SUCCEEDED);
  }

void OnDeinit(const int reason)
  {
   ObjectsDeleteAll(0, "JAX_FORGE_");
  }

void DrawLevelLine(const string objName, const double price, const color clr, const string label)
  {
   if(ObjectFind(0, objName) < 0)
      ObjectCreate(0, objName, OBJ_HLINE, 0, 0, price);
   ObjectSetDouble(0, objName, OBJPROP_PRICE, price);
   ObjectSetInteger(0, objName, OBJPROP_COLOR, clr);
   ObjectSetInteger(0, objName, OBJPROP_WIDTH, InpLineWidth);
   ObjectSetString(0, objName, OBJPROP_TEXT, label);
  }

void DrawSetupPlan(const bool isBuy, const datetime barTime, const double entry, const double sl, const double tp1, const double tp2, const double tp3)
  {
   if(!InpDrawSetupBoxes) return;
   string dir = isBuy ? "BUY" : "SELL";
   DrawLevelLine("JAX_FORGE_ENTRY", entry, InpEntryColor, "JAX " + dir + " ENTRY");
   DrawLevelLine("JAX_FORGE_SL", sl, InpSlColor, "JAX STOP LOSS / INVALIDATION");
   DrawLevelLine("JAX_FORGE_TP1", tp1, InpTp1Color, "JAX TP1 (1.5R)");
   DrawLevelLine("JAX_FORGE_TP2", tp2, InpTp2Color, "JAX TP2 (" + DoubleToString(InpTargetRR, 1) + "R)");
   DrawLevelLine("JAX_FORGE_TP3", tp3, InpTp3Color, "JAX TP3 (3.5R)");
  }

int OnCalculate(const int rates_total,
                const int prev_calculated,
                const datetime &time[],
                const double &open[],
                const double &high[],
                const double &low[],
                const double &close[],
                const long &tick_volume[],
                const long &volume[],
                const int &spread[])
  {
   if(rates_total < InpSlowEma + InpSwingLookback + 5)
      return(0);

   ArraySetAsSeries(time, true);
   ArraySetAsSeries(open, true);
   ArraySetAsSeries(high, true);
   ArraySetAsSeries(low, true);
   ArraySetAsSeries(close, true);

   double atrArr[];
   double htfF[];
   double htfS[];
   ArraySetAsSeries(atrArr, true);
   ArraySetAsSeries(htfF, true);
   ArraySetAsSeries(htfS, true);

   int toCopy = MathMin(rates_total, 200);
   if(CopyBuffer(hFast, 0, 0, toCopy, BufFastEma) <= 0) return(prev_calculated);
   if(CopyBuffer(hSlow, 0, 0, toCopy, BufSlowEma) <= 0) return(prev_calculated);
   if(CopyBuffer(hAtr, 0, 0, toCopy, atrArr) <= 0) return(prev_calculated);
   if(CopyBuffer(hHtfFast, 0, 1, 2, htfF) <= 0) return(prev_calculated);
   if(CopyBuffer(hHtfSlow, 0, 1, 2, htfS) <= 0) return(prev_calculated);

   int startBar = InpClosedCandleOnly ? 1 : 0;
   int maxCheck = MathMin(toCopy - InpSwingLookback - 2, 120);

   for(int i = startBar; i < maxCheck; i++)
     {
      BufBuyArrow[i]  = EMPTY_VALUE;
      BufSellArrow[i] = EMPTY_VALUE;

      double priorLow  = low[i + 1];
      double priorHigh = high[i + 1];
      for(int k = i + 1; k <= i + InpSwingLookback; k++)
        {
         priorLow  = MathMin(priorLow, low[k]);
         priorHigh = MathMax(priorHigh, high[k]);
        }

      double atr = MathMax(atrArr[i], _Point * 10.0);
      bool htfBull = (htfF[0] >= htfS[0]);
      bool htfBear = (htfF[0] <= htfS[0]);

      // Pattern logic: ${pattern.label} with closed-bar non-repainting check
      bool sweepBull = (low[i] < priorLow) && (close[i] > priorLow) && (close[i] > open[i]);
      bool crossBull = (close[i] > BufFastEma[i]) && (BufFastEma[i] > BufSlowEma[i]);
      bool sweepBear = (high[i] > priorHigh) && (close[i] < priorHigh) && (close[i] < open[i]);
      bool crossBear = (close[i] < BufFastEma[i]) && (BufFastEma[i] < BufSlowEma[i]);

      if(htfBull && (sweepBull || crossBull) && close[i + 1] <= BufFastEma[i + 1])
        {
         BufBuyArrow[i] = low[i] - atr * 0.35;
         if(i == startBar && time[i] != lastSignalBar)
           {
            lastSignalBar = time[i];
            double entry = close[i];
            double sl    = MathMin(low[i] - atr * 0.4, entry - atr * 1.4);
            double risk  = MathMax(entry - sl, atr * 0.5);
            DrawSetupPlan(true, time[i], entry, sl, entry + risk * 1.5, entry + risk * InpTargetRR, entry + risk * 3.5);
            Alert("JAX Forge BUY Signal on ", _Symbol, " Entry=", DoubleToString(entry, _Digits));
           }
        }
      else if(htfBear && (sweepBear || crossBear) && close[i + 1] >= BufFastEma[i + 1])
        {
         BufSellArrow[i] = high[i] + atr * 0.35;
         if(i == startBar && time[i] != lastSignalBar)
           {
            lastSignalBar = time[i];
            double entry = close[i];
            double sl    = MathMax(high[i] + atr * 0.4, entry + atr * 1.4);
            double risk  = MathMax(sl - entry, atr * 0.5);
            DrawSetupPlan(false, time[i], entry, sl, entry - risk * 1.5, entry - risk * InpTargetRR, entry - risk * 3.5);
            Alert("JAX Forge SELL Signal on ", _Symbol, " Entry=", DoubleToString(entry, _Digits));
           }
        }
     }

   return(rates_total);
  }
//+------------------------------------------------------------------+
        """.trimIndent()
    }

    fun generatePineScriptV6Source(
        name: String,
        category: ForgeCategory,
        pattern: SetupDrawingPattern,
        mtfTimeframes: List<String>,
        fastPeriod: Int,
        slowPeriod: Int,
        atrPeriod: Int,
        rrTarget: Double,
        drawing: SetupDrawingConfig
    ): String {
        val htf = toPineTimeframe(mtfTimeframes.firstOrNull() ?: "H1")
        val entryHex = sanitizeHex(drawing.entryColorHex, "#D4AF37")
        val slHex = sanitizeHex(drawing.slColorHex, "#EF4444")
        val tp1Hex = sanitizeHex(drawing.tp1ColorHex, "#10B981")
        val tp2Hex = sanitizeHex(drawing.tp2ColorHex, "#34D399")
        val tp3Hex = sanitizeHex(drawing.tp3ColorHex, "#38BDF8")
        val styleExpr = when (drawing.lineStyle) {
            "DASHED" -> "line.style_dashed"
            "DOTTED" -> "line.style_dotted"
            else -> "line.style_solid"
        }

        return """
//@version=6
// Generated by J.A.X. OMNIVERSE — Indicator Forge
// Category: ${category.label} | Pattern: ${pattern.label}
indicator("$name [J.A.X. Forge]", overlay=true, max_lines_count=120, max_boxes_count=80, max_labels_count=80)

// --- Configurable Inputs
confirmTf        = input.timeframe("$htf", "Higher Timeframe Bias")
fastLen          = input.int($fastPeriod, "Fast EMA Period", minval=3)
slowLen          = input.int($slowPeriod, "Slow EMA Period", minval=10)
atrLen           = input.int($atrPeriod, "ATR Volatility Period", minval=5)
swingLookback    = input.int(20, "Swing Liquidity Lookback", minval=5)
targetRR         = input.float(${String.format("%.2f", rrTarget)}, "TP2 Risk:Reward", minval=1.0, step=0.1)
closedCandleOnly = input.bool(${drawing.closedCandleOnly}, "Non-Repainting Closed Candle Only")
showSetupBoxes   = input.bool(${drawing.showRiskRewardBoxes}, "Draw Entry / SL / TP1-TP3 & R:R Boxes")
lineWidth        = input.int(${drawing.lineWidthPx.coerceIn(1, 5)}, "Line Width", minval=1, maxval=5)
drawDuration     = input.int(${drawing.durationBars.coerceIn(5, 100)}, "Target Projection Bars", minval=5)

// --- Colors
cEntry = color.new($entryHex, 0)
cSl    = color.new($slHex, 0)
cTp1   = color.new($tp1Hex, 15)
cTp2   = color.new($tp2Hex, 0)
cTp3   = color.new($tp3Hex, 15)

// --- Core & Non-Repainting MTF Series
fastEma = ta.ema(close, fastLen)
slowEma = ta.ema(close, slowLen)
atrVal  = ta.atr(atrLen)

[htfFast, htfSlow] = request.security(syminfo.tickerid, confirmTf, [ta.ema(close[1], fastLen), ta.ema(close[1], slowLen)], lookahead=barmerge.lookahead_off)
htfBull = htfFast >= htfSlow
htfBear = htfFast <= htfSlow

// --- Pattern Logic: ${pattern.label}
priorLow  = ta.lowest(low, swingLookback)[1]
priorHigh = ta.highest(high, swingLookback)[1]

sweepBull = low < priorLow and close > priorLow and close > open
sweepBear = high > priorHigh and close < priorHigh and close < open
trendBull = ta.crossover(close, fastEma) and fastEma > slowEma
trendBear = ta.crossunder(close, fastEma) and fastEma < slowEma

barReady  = closedCandleOnly ? barstate.isconfirmed : true
buySignal = barReady and htfBull and (sweepBull or trendBull)
sellSignal = barReady and htfBear and (sweepBear or trendBear)

plot(fastEma, "J.A.X. Fast EMA", color=cEntry, linewidth=2)
plot(slowEma, "J.A.X. Slow EMA", color=cTp3, linewidth=2)
plotshape(buySignal, "BUY", shape.triangleup, location.belowbar, cTp2, size=size.small)
plotshape(sellSignal, "SELL", shape.triangledown, location.abovebar, cSl, size=size.small)

drawSetup(bool isBuy, float entry, float sl, float tp1, float tp2, float tp3) =>
    if showSetupBoxes
        int x2 = bar_index + drawDuration
        line.new(bar_index, entry, x2, entry, color=cEntry, width=lineWidth, style=$styleExpr)
        line.new(bar_index, sl, x2, sl, color=cSl, width=lineWidth, style=$styleExpr)
        line.new(bar_index, tp1, x2, tp1, color=cTp1, width=1, style=line.style_dashed)
        line.new(bar_index, tp2, x2, tp2, color=cTp2, width=lineWidth, style=$styleExpr)
        line.new(bar_index, tp3, x2, tp3, color=cTp3, width=1, style=line.style_dashed)
        box.new(bar_index, math.max(entry, sl), x2, math.min(entry, sl), border_color=cSl, bgcolor=color.new($slHex, ${100 - drawing.zoneOpacityPct.coerceIn(5, 60)}))
        box.new(bar_index, math.max(entry, tp2), x2, math.min(entry, tp2), border_color=cTp2, bgcolor=color.new($tp2Hex, ${100 - drawing.zoneOpacityPct.coerceIn(5, 60)}))
        string dirTxt = isBuy ? "BUY" : "SELL"
        label.new(x2, entry, "JAX " + dirTxt + "\nEntry: " + str.tostring(entry, format.mintick) + "\nSL: " + str.tostring(sl, format.mintick) + "\nTP2: " + str.tostring(tp2, format.mintick), color=cEntry, textcolor=color.black, style=label.style_label_left)

if buySignal
    float sl = math.min(low - atrVal * 0.4, close - atrVal * 1.4)
    float risk = math.max(close - sl, atrVal * 0.5)
    float tp1 = close + risk * 1.5
    float tp2 = close + risk * targetRR
    float tp3 = close + risk * 3.5
    drawSetup(true, close, sl, tp1, tp2, tp3)
    alert('{"source":"JAX_Forge","dir":"BUY","symbol":"' + syminfo.ticker + '","tf":"' + timeframe.period + '","entry":' + str.tostring(close) + ',"sl":' + str.tostring(sl) + ',"tp2":' + str.tostring(tp2) + '}', alert.freq_once_per_bar_close)

if sellSignal
    float sl = math.max(high + atrVal * 0.4, close + atrVal * 1.4)
    float risk = math.max(sl - close, atrVal * 0.5)
    float tp1 = close - risk * 1.5
    float tp2 = close - risk * targetRR
    float tp3 = close - risk * 3.5
    drawSetup(false, close, sl, tp1, tp2, tp3)
    alert('{"source":"JAX_Forge","dir":"SELL","symbol":"' + syminfo.ticker + '","tf":"' + timeframe.period + '","entry":' + str.tostring(close) + ',"sl":' + str.tostring(sl) + ',"tp2":' + str.tostring(tp2) + '}', alert.freq_once_per_bar_close)
        """.trimIndent()
    }

    fun validateSource(platform: ForgePlatform, sourceCode: String): ForgeValidationReport {
        val lines = sourceCode.lines()
        val findings = mutableListOf<ForgeValidationFinding>()
        var lookaheadDetected = false

        // Balanced brackets & parentheses check
        var parenBalance = 0
        var braceBalance = 0
        lines.forEachIndexed { idx, line ->
            val trimmed = line.trim()
            if (!trimmed.startsWith("//")) {
                parenBalance += line.count { it == '(' } - line.count { it == ')' }
                braceBalance += line.count { it == '{' } - line.count { it == '}' }
            }
            val ln = idx + 1
            if (platform == ForgePlatform.TRADINGVIEW) {
                if (line.contains("lookahead_on", ignoreCase = true) || line.contains("barmerge.lookahead_on")) {
                    lookaheadDetected = true
                    findings.add(
                        ForgeValidationFinding(
                            lineNumber = ln,
                            severity = "ERROR",
                            message = "Future bar leakage: barmerge.lookahead_on detected.",
                            suggestion = "Replace with lookahead=barmerge.lookahead_off and shift HTF series with [1]."
                        )
                    )
                }
                if (line.contains("alert.freq_all") && !sourceCode.contains("barstate.isconfirmed")) {
                    findings.add(
                        ForgeValidationFinding(
                            lineNumber = ln,
                            severity = "WARNING",
                            message = "Intra-bar alert frequency without barstate.isconfirmed may trigger repainting signals.",
                            suggestion = "Guard trigger conditions with barstate.isconfirmed and alert.freq_once_per_bar_close."
                        )
                    )
                }
            } else {
                if (Regex("""\[\s*i\s*-\s*\d+\s*\]""").containsMatchIn(line) && !trimmed.startsWith("//")) {
                    lookaheadDetected = true
                    findings.add(
                        ForgeValidationFinding(
                            lineNumber = ln,
                            severity = "ERROR",
                            message = "Potential future-bar series access [i - k] when ArraySetAsSeries is true.",
                            suggestion = "Reference closed historical bars using [i + k] rather than [i - k]."
                        )
                    )
                }
            }
        }

        if (parenBalance != 0) {
            findings.add(
                ForgeValidationFinding(
                    lineNumber = lines.size,
                    severity = "ERROR",
                    message = "Unbalanced parentheses detected (delta=$parenBalance).",
                    suggestion = "Check opening and closing parentheses across expressions."
                )
            )
        }

        if (platform == ForgePlatform.TRADINGVIEW) {
            if (!sourceCode.contains("//@version=6")) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = 1,
                        severity = "ERROR",
                        message = "Missing Pine Script v6 version directive (//@version=6).",
                        suggestion = "Add //@version=6 as line 1."
                    )
                )
            }
            if (!sourceCode.contains("indicator(")) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = 1,
                        severity = "ERROR",
                        message = "Missing indicator(...) declaration.",
                        suggestion = "Declare indicator(\"Name\", overlay=true)."
                    )
                )
            }
            if (!sourceCode.contains("barstate.isconfirmed")) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = 1,
                        severity = "WARNING",
                        message = "No barstate.isconfirmed check found — live signals may repaint before bar close.",
                        suggestion = "Gate signals with barstate.isconfirmed for non-repainting setups."
                    )
                )
            }
        } else {
            if (braceBalance != 0) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = lines.size,
                        severity = "ERROR",
                        message = "Unbalanced curly braces { } detected (delta=$braceBalance).",
                        suggestion = "Verify all MQL5 function and loop blocks close cleanly."
                    )
                )
            }
            if (!sourceCode.contains("OnInit(") || !sourceCode.contains("OnCalculate(")) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = 1,
                        severity = "ERROR",
                        message = "MQL5 indicator requires both OnInit() and OnCalculate(...) entry points.",
                        suggestion = "Add standard int OnInit() and int OnCalculate(...) implementations."
                    )
                )
            }
            if (!sourceCode.contains("#property indicator_buffers")) {
                findings.add(
                    ForgeValidationFinding(
                        lineNumber = 1,
                        severity = "WARNING",
                        message = "Missing #property indicator_buffers directive.",
                        suggestion = "Specify #property indicator_buffers N matching SetIndexBuffer calls."
                    )
                )
            }
        }

        val errorCount = findings.count { it.severity == "ERROR" }
        val warningCount = findings.count { it.severity == "WARNING" }
        val repaintRisk = when {
            lookaheadDetected -> "HIGH"
            warningCount > 0 -> "MEDIUM"
            else -> "LOW"
        }
        val passed = errorCount == 0
        val summary = if (passed) {
            "Static validation passed ($warningCount warnings, Repaint Risk: $repaintRisk)."
        } else {
            "Static validation failed: $errorCount error(s), $warningCount warning(s). Repair before download/compile."
        }

        return ForgeValidationReport(
            platform = platform,
            passed = passed,
            repaintRiskLevel = repaintRisk,
            lookaheadDetected = lookaheadDetected,
            findings = findings,
            summary = summary
        )
    }

