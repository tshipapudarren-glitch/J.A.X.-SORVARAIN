    private fun toMql5Period(tf: String): String = when (tf.uppercase()) {
        "M1" -> "PERIOD_M1"
        "M5" -> "PERIOD_M5"
        "M15" -> "PERIOD_M15"
        "M30" -> "PERIOD_M30"
        "H4" -> "PERIOD_H4"
        "D1" -> "PERIOD_D1"
        "W1" -> "PERIOD_W1"
        "MN1" -> "PERIOD_MN1"
        else -> "PERIOD_H1"
    }

    private fun toPineTimeframe(tf: String): String = when (tf.uppercase()) {
        "M1" -> "1"
        "M5" -> "5"
        "M15" -> "15"
        "M30" -> "30"
        "H4" -> "240"
        "D1" -> "D"
        "W1" -> "W"
        "MN1" -> "M"
        else -> "60"
    }

    private fun sanitizeHex(hex: String, fallback: String): String {
        val clean = hex.trim()
        return if (clean.matches(Regex("^#[0-9A-Fa-f]{6}$"))) clean else fallback
    }

    private fun toMql5Color(hex: String, fallback: String): String {
        val clean = hex.trim().removePrefix("#")
        if (clean.length != 6) return fallback
        val r = clean.substring(0, 2).toIntOrNull(16) ?: return fallback
        val g = clean.substring(2, 4).toIntOrNull(16) ?: return fallback
        val b = clean.substring(4, 6).toIntOrNull(16) ?: return fallback
        return "C'$r,$g,$b'"
    }
